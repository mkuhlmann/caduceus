// Packages the desktop app: embeds the built frontend (`dist/`) and compiles main.ts, the relay worker
// and the webview library into one executable per target.
//
//   bun desktop/webview/build.ts                 only write assets.gen.ts, for running main.ts from source
//   bun desktop/webview/build.ts windows-x64     portable zip in desktop/webview/out
//   bun desktop/webview/build.ts linux-x64       tar.gz in desktop/webview/out
import { mkdirSync, readdirSync, rmSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import { deflateRawSync } from 'node:zlib'

const here = import.meta.dir
const root = join(here, '..', '..')
const dist = join(root, 'dist')
const out = join(here, 'out')
const { version } = await Bun.file(join(root, 'package.json')).json()

const targets: Record<string, { bun: string; exe: string; pack: (exe: string) => Promise<string> }> = {
	'windows-x64': { bun: 'bun-windows-x64', exe: 'Caduceus.exe', pack: packWindows },
	'linux-x64': { bun: 'bun-linux-x64', exe: 'caduceus', pack: (exe) => packLinux(exe, 'x64') },
	'linux-arm64': { bun: 'bun-linux-arm64', exe: 'caduceus', pack: (exe) => packLinux(exe, 'arm64') },
}

const wanted = process.argv.slice(2)
for (const t of wanted) {
	if (!targets[t]) {
		console.error(`Unknown target "${t}". Use one of: ${Object.keys(targets).join(', ')}.`)
		process.exit(1)
	}
}

await writeAssetManifest()
for (const t of wanted) {
	const target = targets[t]!
	const stage = join(out, t)
	rmSync(stage, { recursive: true, force: true })
	mkdirSync(stage, { recursive: true })
	const exe = join(stage, target.exe)
	await compile(target.bun, exe)
	const artifact = await target.pack(exe)
	console.log(`${artifact} (${(statSync(artifact).size / 1e6).toFixed(1)} MB)`)
}

/** Every file in dist/, imported as an embedded file and registered with the relay by URL path. */
async function writeAssetManifest() {
	if (!statSync(dist, { throwIfNoEntry: false })?.isDirectory()) {
		console.error('dist/ is missing. Run `bun run build` first.')
		process.exit(1)
	}
	const files = (readdirSync(dist, { recursive: true }) as string[])
		.map((f) => f.replaceAll('\\', '/'))
		.filter((f) => statSync(join(dist, f)).isFile())
		.sort()
	const lines = [
		'// Generated by build.ts from dist/. Do not edit.',
		"import { embedded } from '../../server/embedded'",
		...files.map(
			(f, i) => `import f${i} from '${relative(here, join(dist, f)).replaceAll('\\', '/')}' with { type: 'file' }`,
		),
		...files.map((f, i) => `embedded.set(${JSON.stringify(f)}, f${i})`),
	]
	await Bun.write(join(here, 'assets.gen.ts'), lines.join('\n') + '\n')
}

async function compile(bunTarget: string, outfile: string) {
	const args = [
		'build',
		'--compile',
		`--target=${bunTarget}`,
		'--minify',
		// The app is started from anywhere; a stray .env or bunfig.toml in that folder must not configure it.
		'--no-compile-autoload-dotenv',
		'--no-compile-autoload-bunfig',
		join(here, 'main.ts'),
		join(here, 'server.ts'),
		'--outfile',
		outfile,
	]
	if (bunTarget.startsWith('bun-windows')) args.push('--windows-hide-console')
	const proc = Bun.spawn([process.execPath, ...args], { stdio: ['ignore', 'inherit', 'inherit'] })
	if ((await proc.exited) !== 0) process.exit(1)
}

async function packWindows(exe: string) {
	const notice =
		'This file makes Caduceus portable: settings and data are kept in the "data" folder next to Caduceus.exe.\r\n' +
		'Delete it to store them in your user profile (%APPDATA%\\Caduceus) instead.\r\n'
	const artifact = join(out, `Caduceus-${version}-x64-portable.zip`)
	await Bun.write(
		artifact,
		zip([
			{ name: 'Caduceus.exe', data: await Bun.file(exe).bytes() },
			{ name: 'portable', data: Buffer.from(notice) },
		]),
	)
	return artifact
}

async function packLinux(exe: string, arch: string) {
	const artifact = join(out, `caduceus-${version}-linux-${arch}.tar.gz`)
	const proc = Bun.spawn(['tar', '-czf', artifact, '-C', join(exe, '..'), 'caduceus'], {
		stdio: ['ignore', 'inherit', 'inherit'],
	})
	if ((await proc.exited) !== 0) process.exit(1)
	return artifact
}

/** A plain deflate zip. Enough for two files, and it needs no zip tool on the build machine. */
function zip(entries: { name: string; data: Uint8Array }[]) {
	const now = new Date()
	const time = (now.getHours() << 11) | (now.getMinutes() << 5) | (now.getSeconds() >> 1)
	const date = ((now.getFullYear() - 1980) << 9) | ((now.getMonth() + 1) << 5) | now.getDate()
	const local: Uint8Array[] = []
	const central: Uint8Array[] = []
	let offset = 0
	for (const { name, data } of entries) {
		const nameBytes = Buffer.from(name)
		const packed = deflateRawSync(data, { level: 9 })
		const crc = Bun.hash.crc32(data) >>> 0
		const head = Buffer.alloc(30)
		head.writeUInt32LE(0x04034b50, 0)
		head.writeUInt16LE(20, 4)
		head.writeUInt16LE(0x0800, 6) // UTF-8 names
		head.writeUInt16LE(8, 8) // deflate
		head.writeUInt16LE(time, 10)
		head.writeUInt16LE(date, 12)
		head.writeUInt32LE(crc, 14)
		head.writeUInt32LE(packed.length, 18)
		head.writeUInt32LE(data.length, 22)
		head.writeUInt16LE(nameBytes.length, 26)
		const dir = Buffer.alloc(46)
		dir.writeUInt32LE(0x02014b50, 0)
		dir.writeUInt16LE(20, 4)
		dir.writeUInt16LE(20, 6)
		dir.writeUInt16LE(0x0800, 8)
		dir.writeUInt16LE(8, 10)
		dir.writeUInt16LE(time, 12)
		dir.writeUInt16LE(date, 14)
		dir.writeUInt32LE(crc, 16)
		dir.writeUInt32LE(packed.length, 20)
		dir.writeUInt32LE(data.length, 24)
		dir.writeUInt16LE(nameBytes.length, 28)
		dir.writeUInt32LE(offset, 42)
		local.push(head, nameBytes, packed)
		central.push(dir, nameBytes)
		offset += head.length + nameBytes.length + packed.length
	}
	const end = Buffer.alloc(22)
	end.writeUInt32LE(0x06054b50, 0)
	end.writeUInt16LE(entries.length, 8)
	end.writeUInt16LE(entries.length, 10)
	end.writeUInt32LE(
		central.reduce((n, b) => n + b.length, 0),
		12,
	)
	end.writeUInt32LE(offset, 16)
	return Buffer.concat([...local, ...central, end])
}
