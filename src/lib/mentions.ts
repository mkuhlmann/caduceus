/**
 * @mentions of bots, with Hermes Desktop's rules so a tag means the same bot in both apps:
 * - A bot answers to its handle (`@hermes` for the primary profile, `@<profile>` otherwise), its profile name, and
 *   the slug of its title: "Research Buddy" answers to `@research-buddy` and `@researchbuddy`.
 * - On send, a message that tags bots gets an identification note naming who each tag is. The bot itself then
 *   contacts them with its `message_agent` tool; the user's text is never forwarded verbatim.
 * - A bot's message to another arrives stamped `Message from 🤖 <name> (@<handle>): …` and reads as a notice.
 */

export type MentionTarget = { name: string; handle: string; title: string; displayName: string; isDefault: boolean }

const RESERVED = ['all', 'everyone', 'user', 'default', 'hermes']

/** The tag forms a friendly name gives: its slug and the slug without separators. */
export function nameForms(value: string | null | undefined): string[] {
	const name = String(value ?? '')
		.trim()
		.toLowerCase()
	if (!name) return []
	const slug = name.replace(/[^a-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '')
	const collapsed = name.replace(/[^a-z0-9_-]+/g, '')
	return [...new Set([slug, collapsed])].filter((f) => /^[a-z0-9][a-z0-9_-]*$/.test(f) && !RESERVED.includes(f))
}

/** What autocomplete inserts: the title's tag when the bot has one, else its handle. */
export function mentionTag(bot: MentionTarget) {
	return nameForms(bot.title)[0] ?? bot.handle
}

function formsOf(bot: MentionTarget) {
	return new Set([bot.handle.toLowerCase(), bot.name.toLowerCase(), ...nameForms(bot.title)])
}

/** The bots a text tags, in order, skipping the one being talked to. A tag two bots share resolves to neither. */
export function resolveMentions(text: string, bots: MentionTarget[], active?: string): MentionTarget[] {
	const prose = text.replace(/```[\s\S]*?```/g, ' ').replace(/`[^`\n]*`/g, ' ')
	const byForm = new Map<string, MentionTarget | null>()
	for (const bot of bots) {
		if (bot.name === active) continue
		for (const f of formsOf(bot)) {
			const existing = byForm.get(f)
			byForm.set(f, existing && existing !== bot ? null : bot)
		}
	}
	const out: MentionTarget[] = []
	for (const m of prose.matchAll(/(^|\s)@([a-z0-9][a-z0-9_-]*)/gi)) {
		const bot = byForm.get(m[2]!.toLowerCase())
		if (bot && !out.includes(bot)) out.push(bot)
	}
	return out
}

const NOTE_START = '\n\n[@mentions resolved from the Bot Mode roster — the user is referring to: '

/** Desktop's identification note, appended to a message that tags bots. */
export function mentionNote(mentioned: MentionTarget[]) {
	if (!mentioned.length) return ''
	const lines = mentioned.map((b) => `@${b.handle} = agent profile "${b.name}"${b.title ? ` ("${b.title}")` : ''}`)
	return (
		NOTE_START +
		lines.join('; ') +
		'. If they want one of these agents contacted, compose your own message and send it with your message_agent tool; never forward the user’s text verbatim. If this session has no message_agent tool, agent messaging is unavailable here — say so.]'
	)
}

/** The user's own words, without the note Caduceus or Hermes Desktop appended. */
export function stripMentionNote(text: string) {
	const i = text.indexOf(NOTE_START)
	return i >= 0 ? text.slice(0, i) : text
}

export type BotNotice = { from: string; handle: string; body: string; notifyOnly: boolean }

const NOTICE = /^Message from 🤖 (.+?) \(@([A-Za-z0-9_@.-]+)\): ([\s\S]*)$/

/** A message one bot sent another, recognised by Hermes' sender stamp. */
export function parseBotNotice(text: string): BotNotice | null {
	const m = NOTICE.exec(text.trim())
	if (!m) return null
	let body = m[3]!
	const notifyOnly = body.includes('[no reply needed]')
	body = body.replace(/\s*\[no reply needed\]\s*/g, ' ').trim()
	return { from: m[1]!, handle: m[2]!, body, notifyOnly }
}

/** The text before the caret that is a tag being typed, as `{ start, query }`, or null. */
export function typedMention(text: string, caret: number) {
	const m = /(^|\s)@([a-z0-9_-]*)$/i.exec(text.slice(0, caret))
	if (!m) return null
	return { start: caret - m[2]!.length - 1, query: m[2]!.toLowerCase() }
}

/** Bots matching what is typed after `@`, best first. */
export function mentionCandidates(query: string, bots: MentionTarget[], active?: string) {
	const q = query.toLowerCase()
	return bots
		.filter((b) => b.name !== active)
		.map((b) => {
			const forms = [...formsOf(b), b.displayName.toLowerCase()]
			const rank = forms.some((f) => f.startsWith(q)) ? 0 : forms.some((f) => f.includes(q)) ? 1 : 2
			return { b, rank }
		})
		.filter((x) => x.rank < 2)
		.sort((a, b) => a.rank - b.rank || a.b.displayName.localeCompare(b.b.displayName))
		.map((x) => x.b)
}

export type SystemNotice = { title: string; body: string; details: string }

const INTERNAL = '[INTERNAL NOTIFICATION — generated by the Hermes gateway'

/**
 * A notification Hermes injects into a chat (a finished background delivery, a teammate's reply arriving). It is
 * not something the user wrote, so it reads as a small notice: the outcome and the reply, with the raw text folded.
 */
export function parseSystemNotice(text: string): SystemNotice | null {
	if (!text.includes(INTERNAL) && !/^\[IMPORTANT: Background process /.test(text.trim())) return null
	const details = text.replace(/\n*\[INTERNAL NOTIFICATION[\s\S]*$/, '').trim()
	const json = /\{"outcome"[\s\S]*?\}(?=\s*\]?\s*$|\s*\n)/m.exec(details)?.[0]
	if (json) {
		try {
			const d = JSON.parse(json) as { outcome?: string; reply?: string; status?: string }
			return { title: d.outcome ?? 'A teammate answered.', body: d.reply ?? '', details }
		} catch {}
	}
	const exit = /completed normally|exit code (\d+)/.exec(details)
	return { title: exit ? 'A background task finished.' : 'Hermes posted a notification.', body: '', details }
}
